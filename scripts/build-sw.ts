// Post-build: write dist/sw.js that precaches every built file (offline-first, Section 2).
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const dist = join(process.cwd(), 'dist');
const files: string[] = [];
const walk = (d: string) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (!f.endsWith('.map') && f !== 'sw.js') files.push(relative(dist, p).split('\\').join('/'));
  }
};
walk(dist);
const hash = createHash('sha256');
let total = 0;
for (const f of files.sort()) { const b = readFileSync(join(dist, f)); hash.update(f).update(b); total += b.length; }
const version = hash.digest('hex').slice(0, 12);
const urls = ['./', ...files.map((f) => `./${f}`)];

const sw = `// Generated by scripts/build-sw.ts. Cache-first; everything is precached on install.
const CACHE = 'hahs-${version}';
const URLS = ${JSON.stringify(urls)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(URLS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k !== CACHE) await caches.delete(k);
    await self.clients.claim();
    for (const c of await self.clients.matchAll()) c.postMessage('precached');
  })());
});
self.addEventListener('message', async (e) => {
  const c = await caches.open(CACHE);
  const have = await c.keys();
  if (have.length >= URLS.length && e.source) e.source.postMessage('precached');
});
// Audio/video ask for byte ranges. Safari refuses to play media from a plain 200, so slice
// the cached file into a proper 206 Partial Content response.
async function ranged(req) {
  const hit = await caches.match(req, { ignoreSearch: true, ignoreVary: true });
  if (!hit) return fetch(req);
  const buf = await hit.arrayBuffer();
  const size = buf.byteLength;
  const m = /bytes=(\\d*)-(\\d*)/.exec(req.headers.get('range') || '');
  let start = 0;
  let end = size - 1;
  if (m && m[1]) { start = Number(m[1]); if (m[2]) end = Math.min(size - 1, Number(m[2])); }
  else if (m && m[2]) start = Math.max(0, size - Number(m[2]));
  if (start >= size) return new Response(null, { status: 416, headers: { 'Content-Range': 'bytes */' + size } });
  return new Response(buf.slice(start, end + 1), { status: 206, headers: {
    'Content-Type': hit.headers.get('Content-Type') || 'audio/mpeg',
    'Content-Range': 'bytes ' + start + '-' + end + '/' + size,
    'Content-Length': String(end - start + 1),
    'Accept-Ranges': 'bytes',
  } });
}
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  if (e.request.headers.has('range')) { e.respondWith(ranged(e.request)); return; }
  e.respondWith(caches.match(e.request, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(e.request).catch(() => caches.match('./'))));
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`sw.js: precaching ${urls.length} URLs, ${(total / 1024).toFixed(1)} KB total (version ${version})`);
if (total > 2 * 1024 * 1024) { console.error('Bundle exceeds the ~2 MB budget!'); process.exit(1); }
